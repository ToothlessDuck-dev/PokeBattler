package org.example.input;

public class ConsoleColors {

    public static final String DEFAULT = "\u001B[0m";

    // BRIGHT GREEN
    public static final String SUCCESS = "\u001B[92m";

    // CYAN
    public static final String INFO = "\u001B[96m";

    // BRIGHT YELLOW
    public static final String CHOICES = "\u001B[93m";

    // RED
    public static final String ERROR = "\u001B[31m";

    // BRIGHT RED
    public static final String INVALID = "\u001B[91m";

    // YELLOW
    public static final String WARNING = "\u001B[33";

    // MAGENTA
    public static final String HIGHLIGHT = "\u001B[95m";

    // GREY
    public static final String SEPERATION = "\u001B[90m";

}
